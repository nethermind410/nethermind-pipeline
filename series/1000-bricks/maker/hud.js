const rows = ch => (G[ch] || '').split(' ');
export const known = ch => ch in G;
export const textW = (s, px) => [...s].reduce((w, ch) => w + (ch === ' ' ? 4 : ch === ',' || ch === '.' || ch === "'" || ch === '!' || ch === ':' ? 4 : 6), -1) * px;
// draw s with its centre at cx; px = the size of one tile
export function text(c, s, cx, y, px, col = '#ffffff', shade = 'rgba(0,0,0,0.55)') {
  let x = Math.round(cx - textW(s, px) / 2);
  for (const ch of s) {
    const narrow = ',.\'!:'.includes(ch), r = rows(ch);
    for (let j = 0; j < r.length; j++) for (let i = 0; i < 5; i++) if (r[j][i] === '1') {
      const X = x + (i - (narrow ? 1 : 0)) * px, Y = y + j * px;
      c.fillStyle = shade; c.fillRect(X + px * 0.18, Y + px * 0.22, px, px);
      c.fillStyle = col; c.fillRect(X, Y, px - 1, px - 1);
      c.fillStyle = 'rgba(255,255,255,0.35)'; c.fillRect(X, Y, px - 1, Math.max(1, px * 0.16));
      c.fillStyle = 'rgba(0,0,0,0.28)'; c.fillRect(X, Y + px - 1 - Math.max(1, px * 0.16), px - 1, Math.max(1, px * 0.16));
    }
    x += (ch === ' ' || narrow ? 4 : 6) * px;
  }
}
export const fmt = n => String(Math.round(n)).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
// the counter: the teal brick and the number of bricks he has left
export function counter(c, n, W, pulse = 0) {
  const px = 13, s = fmt(n), w = textW(s, px), bx = W / 2 - w / 2 - 78, by = 150;
  c.fillStyle = 'rgba(5,3,10,0.6)'; c.fillRect(bx - 34, by - 40, w + 146, 172);
  c.fillStyle = 'rgba(0,0,0,0.5)'; c.fillRect(bx + 6, by + 8, 56, 56);
  c.fillStyle = '#19e0c8'; c.fillRect(bx, by, 56, 56); c.fillStyle = '#7ff5e6'; c.fillRect(bx, by, 56, 8); c.fillStyle = '#0a9a8a'; c.fillRect(bx, by + 48, 56, 8);
  c.fillStyle = '#7ff5e6'; c.beginPath(); c.arc(bx + 28, by + 28, 15, 0, 7); c.fill(); c.fillStyle = '#19e0c8'; c.beginPath(); c.arc(bx + 28, by + 30, 13, 0, 7); c.fill();
  text(c, s, W / 2 + 39, by - 16, px, pulse > 0 ? '#7ff5e6' : pulse < 0 ? '#ff6b5e' : '#ffffff');
  text(c, 'bricks left', W / 2, by + 92, 5, '#cfc6e8');
}
